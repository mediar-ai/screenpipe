// screenpipe — AI that knows everything you've seen, said, or heard
// https://screenpipe.com
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const url = process.env.WORKFLOWS_PREVIEW_URL || "http://127.0.0.1:1431/preview";
const out = process.env.WORKFLOW_EDITOR_ARTIFACTS || path.join(require("node:os").tmpdir(), "workflow-step-controls");
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, channel: "chrome" });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(15000);
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    const field = name => page.getByRole("textbox", { name, exact: true });
    const button = name => page.getByRole("button", { name, exact: true });
    const snap = name => page.screenshot({ path: path.join(out, `${name}.png`), animations: "disabled" });
    const saved = () => page.getByRole("status", { name: "Save status" }).filter({ hasText: /^Saved$/ }).waitFor();
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem("screenpipe:fictional-workflow-editor-preview"))?.analysis.workflows.find(w => w.id === "Research synthesis"));
    await page.goto(url, { timeout: 120000 });
    await button("Open map").first().click();
    await field("Workflow title").waitFor();
    const handle = button("Step 1 actions");
    await page.mouse.move(0, 0);
    await page.waitForTimeout(200);
    assert.equal(await handle.evaluate(e => getComputedStyle(e).opacity), "0");
    assert.equal(await handle.evaluate(e => getComputedStyle(e).pointerEvents), "none");
    await snap("after-idle");
    const titleBounds = await field("Step 1 title").boundingBox();
    await field("Step 1 title").hover();
    await page.waitForTimeout(200);
    assert.equal(await handle.evaluate(e => getComputedStyle(e).opacity), "1");
    assert.equal(await button("Step 2 actions").evaluate(e => getComputedStyle(e).opacity), "0");
    await snap("after-hover");
    await handle.hover();
    await snap("after-handle-hover");
    await handle.click();
    await page.getByRole("dialog", { name: "Actions for step 1" }).waitFor();
    assert.deepEqual(await field("Step 1 title").boundingBox(), titleBounds);
    await snap("after");
    await button("Move step 1 down").focus();
    await page.keyboard.press("Tab");
    await snap("after-keyboard");
    await page.keyboard.press("Escape");
    assert(await handle.evaluate(e => e === document.activeElement));
    assert.equal(await page.getByRole("dialog", { name: "Actions for step 1" }).count(), 0);
    await snap("after-handle-focus");
    await handle.click();
    await field("Workflow title").click();
    assert.equal(await page.getByRole("dialog", { name: "Actions for step 1" }).count(), 0);
    await page.mouse.move(0, 0);
    await page.waitForTimeout(200);
    assert.equal(await handle.evaluate(e => getComputedStyle(e).opacity), "0");
    await snap("after-mouse-leave");
    console.log("PASS idle, hover, neighboring controls, focus, Escape, outside click, and stable layout");
    const timing = button("Timing for step 1");
    assert.equal(await timing.locator("..").evaluate(e => getComputedStyle(e).opacity), "0");
    assert.equal(await button("Timing for step 2").count(), 0);
    await field("Step 1 title").hover();
    assert.equal(await timing.innerText(), "5m");
    await timing.click();
    await page.getByRole("tooltip").getByText("5m on average", { exact: true }).waitFor();
    await snap("after-timing");
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("tooltip").count(), 0);
    await field("Workflow title").focus();
    await timing.focus();
    assert.equal(await timing.locator("..").evaluate(e => getComputedStyle(e).opacity), "1");
    await page.keyboard.press("Escape");
    console.log("PASS empty timing omitted; measured timing reveals on hover and keyboard focus");


    await field("Workflow title").fill("Research brief");
    await saved();
    const before = await stored();
    await field("Step 1 title").hover();
    const insert = button("Add step after 1");
    await insert.locator("..").hover();
    await snap("after-insert");
    await insert.click();
    await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Step 2 title");
    await field("Step 2 title").fill("Review the sources");
    await saved();
    const inserted = await stored();
    assert.equal(inserted.stages[1].name, "Review the sources");
    assert.deepEqual(inserted.stages[0].evidence, before.stages[0].evidence);
    assert.deepEqual(inserted.stages[2].evidence, before.stages[1].evidence);
    await button("Step 2 actions").click();
    await button("Delete step 2").click();
    await saved();
    assert.equal((await stored()).stages.length, before.stages.length);
    console.log("PASS insert below, focused title, autosave, delete, and preserved sources");

    await field("Step 1 title").hover();
    await button("Add detail to step 1").click();
    await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Block 4 in step 1");
    await field("Block 4 in step 1").fill("Check each source date.");
    await saved();
    assert.equal((await stored()).stages[0].procedure[3].text, "Check each source date.");
    await handle.focus();
    await page.keyboard.press("Alt+ArrowDown");
    await saved();
    assert.equal((await stored()).stages[1].name, "Collect sources");
    await button("Step 2 actions").focus();
    await page.keyboard.press("Alt+ArrowUp");
    await saved();
    await field("Step 1 title").hover();
    // Keep both complete steps on screen for a real pointer drag.
    await page.setViewportSize({ width: 1440, height: 1900 });
    await handle.dragTo(field("Step 2 title"));
    await saved();
    assert.equal((await stored()).stages[1].name, "Collect sources");
    assert.equal(await page.getByRole("dialog", { name: /^Actions for step/ }).count(), 0);
    await button("More workflow actions").click();
      await page.getByRole("menuitem", { name: "Undo last edit", exact: true }).click();
    await saved();
    await page.reload();
    await button("Open map").first().click();
    assert.equal(await field("Step 1 title").inputValue(), "Collect sources");
    assert.equal(await field("Workflow title").inputValue(), "Research brief");
    console.log("PASS add block, keyboard and drag reorder, undo, reload persistence");

    const context = await browser.newContext({ viewport: { width: 390, height: 900 }, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
    const touch = await context.newPage();
    await touch.goto(url);
    await touch.getByRole("button", { name: "Open map", exact: true }).first().tap();
    const touchHandle = touch.getByRole("button", { name: "Step 1 actions", exact: true });
    assert.equal(await touchHandle.evaluate(e => getComputedStyle(e).opacity), "1");
    assert.equal(await touch.getByRole("button", { name: "Timing for step 2", exact: true }).count(), 0);
    const touchTiming = touch.getByRole("button", { name: "Timing for step 1", exact: true });
    await touchTiming.tap();
    await touch.getByRole("tooltip").getByText("5m on average", { exact: true }).waitFor();
    await touch.getByRole("textbox", { name: "Workflow title", exact: true }).tap();
    await touchHandle.tap();
    const menu = touch.getByRole("dialog", { name: "Actions for step 1" });
    const bounds = await menu.boundingBox();
    assert(bounds.x >= 0 && bounds.x + bounds.width <= 390);
    await touch.screenshot({ path: path.join(out, "after-touch.png"), animations: "disabled" });
    await touch.getByRole("button", { name: "Add step below", exact: true }).tap();
    await touch.getByRole("textbox", { name: "Step 2 title", exact: true }).waitFor();
    console.log("PASS narrow touch controls, menu bounds, insertion, reduced motion");
    await context.close();
    assert.deepEqual(errors, []);
    console.log("PASS no browser exceptions");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
